#!/usr/bin/env node
// Builds composition/index.html (the HyperFrames composition) from scenes.mjs.
// Screen scenes use composition/assets/scenes/<id>.mp4 from capture.mjs; a missing clip becomes a placeholder.
//
//   node compose.mjs && npx hyperframes render composition --output out/demo-draft.mp4

import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CROSSFADE, FPS, SCENES, totalDuration } from "./scenes.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const COMP = path.join(HERE, "composition");

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const r3 = (n) => Math.round(n * 1000) / 1000;

let t = 0;
const timed = SCENES.map((s, i) => {
  const start = r3(t);
  t += s.duration - CROSSFADE;
  return { ...s, start, z: i + 1, n: i };
});
const total = r3(totalDuration());

let screenNo = 0;
const markup = timed
  .map((s) => {
    const win = `data-start="${s.start}" data-duration="${s.duration}"`;
    const bg = `<div id="bg-${s.id}" class="clip bg" ${win} data-track-index="0" style="z-index:${s.z * 10}"></div>`;
    if (s.kind === "card") {
      return `${bg}
      <section id="card-${s.id}" class="clip card${s.id === "outro" ? " outro" : ""}" ${win} data-track-index="1" style="z-index:${s.z * 10 + 1}">
        <p class="eyebrow">${esc(s.eyebrow)}</p>
        <h1 class="title">${esc(s.title)}</h1>
        <p class="subtitle">${esc(s.subtitle)}</p>
      </section>`;
    }
    screenNo++;
    const clip = path.join(COMP, "assets/scenes", `${s.id}.mp4`);
    const media = existsSync(clip)
      ? `<video id="vid-${s.id}" class="screen" src="assets/scenes/${s.id}.mp4" ${win} data-track-index="2" muted playsinline style="z-index:${s.z * 10 + 1}"></video>`
      : `<div id="vid-${s.id}" class="clip screen placeholder" ${win} data-track-index="2" style="z-index:${s.z * 10 + 1}"><span>Captura pendiente · ${esc(s.id)} · ${esc(s.route)}</span></div>`;
    return `${bg}
      ${media}
      <div id="cap-${s.id}" class="clip caption" ${win} data-track-index="3" style="z-index:${s.z * 10 + 2}">
        <span class="step">${String(screenNo).padStart(2, "0")}</span><span class="text">${esc(s.caption)}</span>
      </div>`;
  })
  .join("\n      ");

const anim = timed
  .map((s) => {
    const ids = s.kind === "card" ? [`#bg-${s.id}`, `#card-${s.id}`] : [`#bg-${s.id}`, `#vid-${s.id}`, `#cap-${s.id}`];
    const lines = [];
    if (s.n > 0) lines.push(`tl.fromTo(${JSON.stringify(ids.join(","))}, { opacity: 0 }, { opacity: 1, duration: ${CROSSFADE}, ease: "power1.inOut" }, ${s.start});`);
    if (s.kind === "card") {
      lines.push(
        `tl.fromTo("#card-${s.id} > *", { y: 28, opacity: 0 }, { y: 0, opacity: 1, duration: 0.8, ease: "power3.out", stagger: 0.14 }, ${r3(s.start + 0.15)});`,
      );
    } else {
      lines.push(`tl.fromTo("#vid-${s.id}", { scale: 0.985 }, { scale: 1.01, duration: ${s.duration}, ease: "none" }, ${s.start});`);
      lines.push(`tl.fromTo("#cap-${s.id} > *", { y: 14, opacity: 0 }, { y: 0, opacity: 1, duration: 0.6, ease: "power2.out", stagger: 0.08 }, ${r3(s.start + 0.35)});`);
    }
    return lines.join("\n      ");
  })
  .join("\n      ");

const html = `<!doctype html>
<!-- GENERATED by compose.mjs from scenes.mjs. Edit those, not this file. -->
<html lang="es">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <style>
      @font-face {
        font-family: "Geist";
        src: url("assets/fonts/geist-latin.woff2") format("woff2");
        font-weight: 100 900;
        font-display: block;
      }
      :root {
        --ground: oklch(1 0 0);
        --ink: oklch(0.205 0 0);
        --muted: oklch(0.52 0 0);
        --border: oklch(0.922 0 0);
        --accent: oklch(0.37 0.07 158);
        --font: "Geist", ui-sans-serif, system-ui, -apple-system, "Helvetica Neue", sans-serif;
      }
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: 1920px; height: 1080px; overflow: hidden; background: var(--ground); }
      #root { position: relative; width: 1920px; height: 1080px; overflow: hidden; font-family: var(--font); color: var(--ink); background: var(--ground); }
      .clip { position: absolute; inset: 0; }
      .bg { background: var(--ground); }

      .card { display: flex; flex-direction: column; justify-content: center; padding: 0 200px; gap: 28px; }
      .eyebrow { font-size: 26px; font-weight: 500; letter-spacing: 0.08em; text-transform: uppercase; color: var(--accent); }
      .title { font-size: 104px; font-weight: 600; letter-spacing: -0.035em; line-height: 1.02; max-width: 1400px; }
      .subtitle { font-size: 38px; font-weight: 400; color: var(--muted); max-width: 1300px; line-height: 1.3; }
      .outro .title { font-size: 84px; }
      .outro .subtitle { color: var(--accent); font-weight: 500; }

      .screen {
        position: absolute; left: 160px; top: 40px; width: 1600px; height: 900px;
        border-radius: 14px; border: 1px solid var(--border); object-fit: cover;
        box-shadow: 0 30px 70px -40px rgba(0, 0, 0, 0.35);
        transform-origin: 50% 40%;
      }
      .placeholder { display: grid; place-items: center; background: oklch(0.97 0 0); border-style: dashed; }
      .placeholder span { font-size: 32px; color: var(--muted); }

      .caption { inset: auto 0 0 0; height: 140px; display: flex; align-items: center; justify-content: center; gap: 18px; }
      .caption .step { font-size: 22px; font-weight: 600; color: var(--accent); font-variant-numeric: tabular-nums; letter-spacing: 0.04em; }
      .caption .text { font-size: 36px; font-weight: 500; letter-spacing: -0.01em; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-fps="${FPS}" data-width="1920" data-height="1080">
      ${markup}
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      const tl = gsap.timeline({ paused: true });
      ${anim}
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`;

writeFileSync(path.join(COMP, "index.html"), html);
const missing = timed.filter((s) => s.kind === "screen" && !existsSync(path.join(COMP, "assets/scenes", `${s.id}.mp4`)));
console.log(`composition/index.html: ${timed.length} scenes, ${total}s${missing.length ? ` (placeholders: ${missing.map((s) => s.id).join(", ")})` : ""}`);
