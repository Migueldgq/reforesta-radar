// Usage: in a scratch dir run `npm i es-atlas@0.6.0 d3-geo d3-composite-projections topojson-client topojson-simplify`, then from that dir `node <repo>/scripts/build-spain-map.mjs > <repo>/src/components/radar/spain-map-data.ts`.
//
// Pre-projects Spain's autonomous communities into static SVG paths so the app ships no map library.
// Geometry: es-atlas (MIT) built from IGN / CNIG "Líneas límite" data, licensed CC BY 4.0 (© Instituto Geográfico Nacional).
// Projection: d3-composite-projections geoConicConformalSpain (Canarias in an inset bottom-left).
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const require = createRequire(`${process.cwd()}/`);
const load = (m) => import(pathToFileURL(require.resolve(m)).href);

const topo = require("es-atlas/es/autonomous_regions.json");
const { feature } = await load("topojson-client");
const { presimplify, simplify, quantile } = await load("topojson-simplify");
const { geoPath } = await load("d3-geo");
// The package is "type": "module" but its UMD bundle is CommonJS-shaped, so evaluate it with a CJS shim.
const umd = {};
new Function("exports", "module", "require", readFileSync(require.resolve("d3-composite-projections"), "utf8"))(umd, {}, require);
const { geoConicConformalSpain } = umd;

const SIZE = 600;
const PAD = 6;

// IGN names -> the region strings used in our data (src/lib/regions.ts).
const NAMES = {
  "Andalucía": "Andalucía",
  "Aragón": "Aragón",
  "Principado de Asturias": "Asturias",
  "Illes Balears": "Illes Balears",
  "Canarias": "Canarias",
  "Cantabria": "Cantabria",
  "Castilla y León": "Castilla y León",
  "Castilla-La Mancha": "Castilla-La Mancha",
  "Cataluña/Catalunya": "Cataluña",
  "Comunitat Valenciana": "Comunitat Valenciana",
  "Extremadura": "Extremadura",
  "Galicia": "Galicia",
  "Comunidad de Madrid": "Comunidad de Madrid",
  "Región de Murcia": "Región de Murcia",
  "Comunidad Foral de Navarra": "Navarra",
  "País Vasco/Euskadi": "País Vasco",
  "La Rioja": "La Rioja",
  "Ciudad Autónoma de Ceuta": "Ceuta",
  "Ciudad Autónoma de Melilla": "Melilla",
};

const simple = simplify(presimplify(topo), quantile(presimplify(topo), 0.35));
const fc = feature(simple, simple.objects.autonomous_regions);
const projection = geoConicConformalSpain().fitSize([SIZE, SIZE], fc);
const path = geoPath(projection);
// Crop to the drawn shapes so the viewBox has no empty margin.
const [[x0, y0], [x1, y1]] = path.bounds(fc);
const [tx, ty] = projection.translate();
projection.translate([tx - x0 + PAD, ty - y0 + PAD]);
const W = Math.ceil(x1 - x0 + 2 * PAD);
const H = Math.ceil(y1 - y0 + 2 * PAD);
const round = (s) => s.replace(/(\d+\.\d+)/g, (n) => (+n).toFixed(1)).replace(/\.0(?=\D|$)/g, "");

const out = [];
const unmapped = [];
for (const f of fc.features) {
  const name = NAMES[f.properties.name];
  if (!name) {
    unmapped.push(f.properties.name);
    continue;
  }
  const [cx, cy] = path.centroid(f);
  // Ceuta and Melilla are too small to see: draw them as small round markers.
  const tiny = name === "Ceuta" || name === "Melilla";
  const d = tiny
    ? `M${(cx - 8).toFixed(1)},${cy.toFixed(1)}a8,8 0 1,0 16,0a8,8 0 1,0 -16,0Z`
    : round(path(f));
  // Marker labels sit above the dot so the dot stays visible.
  out.push({ id: f.id, name, d, labelX: +cx.toFixed(1), labelY: +(tiny ? cy - 20 : cy).toFixed(1) });
}
if (unmapped.length) console.error("Skipped (no region name):", unmapped.join(", "));
out.sort((a, b) => a.name.localeCompare(b.name, "es"));

const border = round(projection.getCompositionBorders());

process.stdout.write(`// Generated by scripts/build-spain-map.mjs. Do not edit by hand.
// Geometry: es-atlas (MIT) from IGN / CNIG boundary data, CC BY 4.0 (© Instituto Geográfico Nacional de España).

export interface MapRegion {
  id: string;
  /** Matches Opportunity.region exactly. */
  name: string;
  d: string;
  labelX: number;
  labelY: number;
}

export const MAP_WIDTH = ${W};
export const MAP_HEIGHT = ${H};

/** Frame around the Canarias inset. */
export const INSET_BORDER = ${JSON.stringify(border)};

export const MAP_REGIONS: MapRegion[] = ${JSON.stringify(out, null, 1)};
`);
